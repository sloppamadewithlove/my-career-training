def shot_definition(scenario_id):
    """Return fresh actor states without changing the source's launch speed."""
    shot = next(shot for shot in _SHOTS if shot["id"] == scenario_id)
    pitch, yaw, _ = (value * math.tau / 65536 for value in shot["ball_rotation"])
    speed = shot["ball_speed"]
    ball = {
        "position": list(shot["ball_position"]),
        "velocity": [speed * math.cos(pitch) * math.cos(yaw),
                     speed * math.cos(pitch) * math.sin(yaw), speed * math.sin(pitch)],
        "angular_velocity": [0.0, 0.0, 0.0],
    }
    car = {
        "position": list(shot["car_position"]),
        "rotation": [value * math.tau / 65536 for value in shot["car_rotation"]],
        "velocity": [0.0, 0.0, 0.0], "angular_velocity": [0.0, 0.0, 0.0], "boost": 100.0,
    }
    return deepcopy(shot), car, ball
